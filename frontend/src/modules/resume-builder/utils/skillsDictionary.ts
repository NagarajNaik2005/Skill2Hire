/**
 * Autocomplete matching function that intelligently ranks:
 * 1. Exact start with query (e.g., "A" -> "AWS", "Angular", "Apache...")
 * 2. Word start match (e.g., "Cloud" -> "AWS CloudFront", "Google Cloud")
 * 3. Substring match (e.g., "script" -> "TypeScript", "JavaScript")
 */
export const getSkillSuggestions = (
  query: string,
  alreadySelected: string[] = [],
  category: 'languages' | 'frameworks' | 'databases' | 'tools' | 'soft' | 'all' = 'all',
  limit: number = 8
): string[] => {
  const cleanQuery = query.trim();
  if (!cleanQuery) return [];

  const lowerQ = cleanQuery.toLowerCase();
  const selectedSet = new Set(alreadySelected.map(s => s.toLowerCase().trim()));

  const candidatePool = SKILL_CATEGORIES_MAP[category] || ALL_TECH_SKILLS;

  const exactStartMatches: string[] = [];
  const wordStartMatches: string[] = [];
  const substringMatches: string[] = [];

  for (const skill of candidatePool) {
    const lowerSkill = skill.toLowerCase();
    
    // Skip if already in the input tags
    if (selectedSet.has(lowerSkill)) continue;

    if (lowerSkill.startsWith(lowerQ)) {
      exactStartMatches.push(skill);
    } else {
      // Check if any word in the skill name starts with query (e.g. "AWS DynamoDB" -> "Dynamo")
      const words = lowerSkill.split(/[\s/()\-_]+/);
      if (words.some(w => w.startsWith(lowerQ))) {
        wordStartMatches.push(skill);
      } else if (lowerSkill.includes(lowerQ)) {
        substringMatches.push(skill);
      }
    }

    if (exactStartMatches.length >= limit * 2) {
      // Early break if we have plenty of high-priority prefix matches
      break;
    }
  }

  // Combine results in order of relevance: Prefix -> Word Start -> Substring
  const combined = [...exactStartMatches, ...wordStartMatches, ...substringMatches];

  // Return deduplicated top results
  return Array.from(new Set(combined)).slice(0, limit);
};
